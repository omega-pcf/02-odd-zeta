"""`bridge.py` behind the bridge-boost statements of the corpus.

Sites covered (statement line numbers as measured — snapshots, the convention
of `docs/numerical-port.md`):

* ``04-bridges:1049-1050`` — "A quadruple placed at $\\gamma=20$ with
  $\\delta=0.1$ contributes the eigenvalues $-1.4\\cdot10^{-4}$ and
  $+5.3\\cdot10^{-4}$, a hyperbolic plane; the translation by $\\log7$ scales
  its two members by $1.2148$ and $0.8232$, with product $1$
  (\\code{bridge.py} \\witness[...]{N})" — prop:bridge-boosts (i) and (ii)
  evaluated at the quadruple of the sentence.
* ``appendix:582`` — the prop:bridge-boosts row naming ``bridge.py`` as its
  numerical carrier.

``bridge.py`` is the one script of this wave with a committed output:
``tests/fixtures/salidas/bridge.txt``, regenerated by ``correr_todo.sh``
(the script and its runner were removed with the port). So it gets the
two-part pattern the F10 wave established: a ``golden`` test that pins the
artifact, and claim tests that recompute the quadruple from first principles
and reconcile each figure against the manuscript text itself (the figures are
parsed from the .tex, never typed into the test).

Conditions declared by the corpus: the quadruple sits at
$\\gamma=20$, $\\delta=0.1$ (parsed from the sentence), the translation is by
$\\log 7$, and the basis is the eight test modes of ``gram.py``
(``J = 8``, ``bridge.py``'s own constant — the manuscript declares the mode
count only for the archimedean sweep).
"""

from __future__ import annotations

import cmath
import math
import re

import numpy as np
import pytest

from oddzeta.harness import GOLDEN_TOL, assert_close, assert_half_last_digit, read_salidas, read_tex

#: bridge.py's own constants: the eight modes of gram.py and the quadruple.
J_MODES = 8
GAMMA, DELTA = 20.0, 0.1


def _claim(pattern: str, note: str) -> re.Match[str]:
    """The manuscript text behind a claim (fails loudly if it is gone)."""
    m = re.search(pattern, read_tex("04-bridges.tex"))
    assert m is not None, f"{note} is no longer in 04-bridges.tex"
    return m


def _groups(pattern: str, text: str, note: str) -> tuple[str, ...]:
    """The capture groups of a pattern in a committed artifact (or fail)."""
    m = re.search(pattern, text)
    assert m is not None, f"{note} is missing from the artifact"
    return m.groups()


def _ghat(z: complex) -> np.ndarray:
    """The eight test modes: ghat_0 = T^, ghat_j = 2cos(jz) T^, T^ = (sin(z/2)/(z/2))^2."""
    T = (cmath.sin(z / 2) / (z / 2)) ** 2
    return np.array([T if j == 0 else 2 * cmath.cos(j * z) * T for j in range(J_MODES)])


def _heights() -> tuple[complex, ...]:
    """The four heights of the quadruple: +-gamma +- i delta (bridge.py's order)."""
    return (
        complex(GAMMA, -DELTA),
        complex(-GAMMA, -DELTA),
        complex(-GAMMA, DELTA),
        complex(GAMMA, DELTA),
    )


def _weil_matrix() -> np.ndarray:
    """C = sum ghat(gamma_rho) ghat(gamma_rho)^T over the four heights."""
    C = np.zeros((J_MODES, J_MODES), dtype=complex)
    for z in _heights():
        C += np.outer(_ghat(z), _ghat(z))
    return C


def _nonzero_eigenvalues() -> np.ndarray:
    """The eigenvalues above the script's 1e-12 * max threshold (the rank-2 part)."""
    C = _weil_matrix()
    ev = np.linalg.eigvalsh(C.real)
    return ev[np.abs(ev) > 1e-12 * np.max(np.abs(ev))]


def _log7_moduli() -> tuple[float, float]:
    """|exp(i log7 gamma_rho)| for the two members of the quadruple, script order."""
    a = math.log(7)
    f1 = abs(cmath.exp(1j * a * complex(GAMMA, -DELTA)))
    f2 = abs(cmath.exp(1j * a * complex(GAMMA, DELTA)))
    return f1, f2


@pytest.mark.golden
def test_bridge_boosts_golden_values() -> None:
    """Pin ``salidas/bridge.txt``: any drift in the artifact fails here."""
    art = read_salidas("bridge.txt")

    imag, note = _groups(r"parte imaginaria de C: ([\d.eE+-]+) \(([^)]+)\)", art, "the imaginary part")
    assert_close(float(imag), 0.0, GOLDEN_TOL, note=f"bridge.txt: {note}")

    neg, pos, rank, sig_p, sig_n = _groups(
        r"autovalores no nulos de C: ([\d.eE+-]+), ([\d.eE+-]+)\s+"
        r"\(rango (\d+), signatura \((\d+),(\d+)\)\)",
        art,
        "the nonzero eigenvalues",
    )
    assert_close(float(neg), -1.41e-04, GOLDEN_TOL, note="bridge.txt: first nonzero eigenvalue")
    assert_close(float(pos), 5.31e-04, GOLDEN_TOL, note="bridge.txt: second nonzero eigenvalue")
    assert (int(rank), int(sig_p), int(sig_n)) == (2, 1, 1), "bridge.txt: rank or signature drifted"

    mod1, mod2, product, rapidity = _groups(
        r"traslacion por log 7: modulos ([\d.]+) y ([\d.]+), producto ([\d.]+); "
        r"rapidez delta log p = ([\d.]+)",
        art,
        "the translation line",
    )
    assert_close(float(mod1), 1.2148, GOLDEN_TOL, note="bridge.txt: first modulus")
    assert_close(float(mod2), 0.8232, GOLDEN_TOL, note="bridge.txt: second modulus")
    assert_close(float(product), 1.000000, GOLDEN_TOL, note="bridge.txt: product of the moduli")
    assert_close(float(rapidity), 0.1946, GOLDEN_TOL, note="bridge.txt: boost rapidity")

    art_ev1, art_ev2, art_m1, art_m2, art_prod = _groups(
        r"articulo: (-?[\d.eE+-]+) y ([\d.eE+-]+); ([\d.]+) y ([\d.]+), producto ([\d.]+)",
        art,
        "the article line",
    )
    assert (float(art_ev1), float(art_ev2)) == (-1.4e-4, 5.3e-4), "bridge.txt: article eigenvalues"
    assert (float(art_m1), float(art_m2), float(art_prod)) == (1.2148, 0.8232, 1.0), (
        "bridge.txt: article moduli"
    )


def test_bridge_quadruple_is_a_hyperbolic_plane() -> None:
    """``04-bridges:1049`` — the eigenvalues $-1.4\\cdot10^{-4}$, $+5.3\\cdot10^{-4}$."""
    gamma = float(_claim(r"quadruple placed at \$\\gamma=([\d.]+)\$", "the quadruple placement").group(1))
    delta = float(_claim(r"with \$\\delta=([\d.]+)\$", "the quadruple placement").group(1))
    assert (gamma, delta) == (GAMMA, DELTA), "the manuscript moved the quadruple"

    m = _claim(
        r"eigenvalues\s+\$(-?[\d.]+)\\cdot10\^\{(-?\d+)\}\$ and \$\+?([\d.]+)\\cdot10\^\{(-?\d+)\}\$",
        "the quadruple eigenvalues",
    )
    negative, positive = f"{m.group(1)}e{m.group(2)}", f"{m.group(3)}e{m.group(4)}"

    C = _weil_matrix()
    assert np.max(np.abs(C.imag)) <= 1e-15, "C is no longer a real form"
    ev = np.sort(_nonzero_eigenvalues())
    assert len(ev) == 2, f"the quadruple contributes {len(ev)} nonzero eigenvalues, not 2"
    assert ev[0] < 0 < ev[1], "the two members no longer span a hyperbolic plane"
    assert_half_last_digit(float(ev[0]), negative, "04-bridges:1049 negative member")
    assert_half_last_digit(float(ev[1]), positive, "04-bridges:1049 positive member")


def test_bridge_log_seven_scales_the_members_as_the_manuscript_says() -> None:
    """``04-bridges:1050`` — $1.2148$ and $0.8232$, product $1$ (a boost)."""
    m = _claim(
        r"members by \$([\d.]+)\$ and \$([\d.]+)\$, with product \$([\d.]+)\$",
        "the log-7 scaling of the two members",
    )
    f1, f2 = _log7_moduli()
    assert_half_last_digit(f1, m.group(1), "04-bridges:1050 first member")
    assert_half_last_digit(f2, m.group(2), "04-bridges:1050 second member")
    # The manuscript states the product as exactly 1 (prop:bridge-boosts (i):
    # the moduli are 7^{+-delta}, reciprocal by construction), so the assertion
    # is float exactness rather than the 5% figure margin.
    assert abs(f1 * f2 - float(m.group(3))) <= 1e-12, (
        f"the two moduli multiply to {f1 * f2!r}, the manuscript says {m.group(3)}"
    )
